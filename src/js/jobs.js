const PUBLISHED_JOBS_STORAGE_KEY = "khattwa-published-jobs";

const PUBLISH_EMPLOYMENT_LABELS = {
  "emp-ft": "دوام كامل",
  "emp-pt": "دوام جزئي",
  "emp-rm": "عن بُعد",
  "emp-in": "تدريب تعاوني",
};

const PUBLISH_EXPERIENCE_LABELS = {
  "ex-0": "بدون خبرة",
  "ex-1": "أقل من سنة",
  "ex-13": "1–3 سنوات",
  "ex-3": "أكثر من 3 سنوات",
};

function readPublishedJobPayloads() {
  try {
    const raw = localStorage.getItem(PUBLISHED_JOBS_STORAGE_KEY);
    const rows = JSON.parse(raw || "[]");
    return Array.isArray(rows) ? rows : [];
  } catch {
    return [];
  }
}

function publishedPayloadToJob(p) {
  const numericId = typeof p.numericId === "number" ? p.numericId : null;
  if (numericId == null) return null;

  const empIds = Array.isArray(p.employment) ? p.employment : [];
  const tags = empIds.map((id) => PUBLISH_EMPLOYMENT_LABELS[id]).filter(Boolean);

  let expKey = "";
  if (typeof p.experience === "string") expKey = p.experience;
  else if (Array.isArray(p.experience) && p.experience.length) expKey = p.experience[0];
  const experienceLabel = PUBLISH_EXPERIENCE_LABELS[expKey] || "غير محدد";

  const loc = [p.locCity, p.locCountry]
    .map((x) => String(x || "").trim())
    .filter(Boolean)
    .join("، ");

  const desc = String(p.jobDescription || "").trim();

  const sectorTrim = String(p.sector || "").trim();
  const locAbout = [p.locCity, p.locCountry]
    .map((x) => String(x || "").trim())
    .filter(Boolean)
    .join("، ");
  const titleShort = String(p.jobTitle || "").trim();
  const catTrim = String(p.jobCategory || "").trim();
  const rolePhrase = titleShort ? `المسمى المعروض هو «${titleShort}»` : "تفاصيل الدور مبيّنة في أقسام الإعلان أعلاه";
  const catPhrase = catTrim ? `، ضمن تصنيف يقترب من «${catTrim}» حسب ما اختاره صاحب الإعلان` : "";

  let aboutCompany = "";
  if (sectorTrim && locAbout) {
    aboutCompany = `«${sectorTrim}» جهة يُعلَن عن فرصة عمل لديها من موقع العمل المذكور (${locAbout}). قسم «عن الشركة» يُفترض أن يقدّم لمحة عن نشاط المنظمة، حجم الفريق أو مراحل النمو، القطاع والعملاء النموذجيين، وثقافة العمل أو سياسات الدوام؛ وفي هذا الإعلان لم يُرفق وصف تعريفي مطوّل من صاحب العمل، لذا تعتمد القراءة الأولى على «النظرة العامة» و«الوصف الوظيفي». ${rolePhrase}${catPhrase}. إذا احتجتَ معلومات إضافية—مثل تقارير الهيكل التنظيمي، طبيعة الإشراف، الأدوات المستخدمة، أو توقعات الأداء في الأشهر الأولى—فاستخدم التواصل عبر المنصة أو خطوة التقديم لطرح أسئلة محددة، مع الحرص على توثيق أي توضيحات رسمية لاحقًا.`;
  } else if (sectorTrim) {
    aboutCompany = `«${sectorTrim}» هي الاسم الذي يظهر كجهة العمل في هذا الإعلان؛ دون أن يُرفق هنا نصًا موسّعًا عن تاريخ المنشأة أو مجال تخصصها أو قيمها أو طبيعة فرق العمل. لتقييم الملاءمة، اربط بين هذا الاسم وباقي أقسام الإعلان: ${rolePhrase}${catPhrase}. الأجزاء التفصيلية عن المهام والمتطلبات تظل مرجعك الأساسي قبل التقديم؛ ولملء الفجوة التعريفية عن الشركة يُفضّل طرح أسئلة موجهة عبر رسائل المنصة (حجم الفريق، مقر العمل الفعلي مقابل عن بُعد، سياسات الإجازات أو التدريب عند توفرها).`;
  } else {
    aboutCompany =
      "لم يُرفق اسم جهة عمل واضح أو نبذة تعريفية عن الشركة مع هذا الإعلان، وهو ما يحدّ من الصورة الكاملة قبل التقديم. راجع «النظرة العامة» و«الوصف الوظيفي» لفهم ما يُتوقع من الدور والمهارات والظروف العملية؛ ثم قرّر ما إذا كنت بحاجة لمعلومات هوية المنشأة (الاسم القانوني، القطاع، الترخيص، أو مقر العمل) قبل المضي قدمًا. استخدم التواصل عبر المنصة لطلب هذه التفاصيل صراحةً، وتجنّب افتراضات غير مؤكدة حول صاحب العمل عندما لا تكون البيانات متوفرة في الإعلان نفسه.";
  }

  return {
    id: numericId,
    title: String(p.jobTitle || "وظيفة").trim() || "وظيفة",
    company: sectorTrim || "صاحب عمل",
    location: loc || "—",
    salary: p.salaryAmount ? `${String(p.salaryAmount).trim()} ر.س / شهريًا` : "حسب الاتفاق",
    roleIcon: "default",
    image: "./src/images/logo/icon.png",
    tags: tags.length ? tags : ["دوام كامل"],
    posted: "الآن",
    employmentType: tags[0] || "دوام كامل",
    experience: experienceLabel,
    overview: desc.length > 220 ? `${desc.slice(0, 220)}…` : desc || "لا توجد نظرة عامة.",
    description: desc ? [desc] : ["لا يوجد وصف تفصيلي بعد."],
    offers: ["راجع التفاصيل مع صاحب العمل عبر المنصة."],
    aboutCompany,
    languages: ["ar"],
    postedDays: 0,
    education: p.fieldEducation ? [String(p.fieldEducation)] : ["غير محدد"],
    distanceKm: 0,
    salaryValue: Number(String(p.salaryAmount || "").replace(/[^\d.]/g, "")) || 0,
    companyVerified: false,
  };
}

function getJobsList() {
  const publishedJobs = readPublishedJobPayloads()
    .slice()
    .reverse()
    .map(publishedPayloadToJob)
    .filter(Boolean);
  return [...publishedJobs, ...JOBS];
}

