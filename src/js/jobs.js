function escapeHtml(str) {
  return String(str)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function renderTag(tag) {
  const primaryTags = new Set(["دوام كامل", "دوام جزئي", "عقد"]);
  const cls = primaryTags.has(tag)
    ? "rounded-md bg-button px-2 py-1 text-xs font-bold text-white dark:text-button-text-dark"
    : "rounded-md bg-card dark:bg-card-dark px-2 py-1 text-xs font-bold text-primaryHeading dark:text-button border border-button/10 dark:border-button/30";
  return `<span class="${cls}">${escapeHtml(tag)}</span>`;
}

