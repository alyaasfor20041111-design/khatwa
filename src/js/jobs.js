function getCheckedValues(group) {
  return Array.from(document.querySelectorAll(`input[data-filter="${group}"]:checked`)).map((el) => el.value);
}
function filterJobs(jobs) {
  const langs = getCheckedValues("language");
  const edu = getCheckedValues("education");
  const jobTypes = getCheckedValues("jobType");
  const workModes = getCheckedValues("workMode");

  const pubEl = document.querySelector('input[name="pub"]:checked');
  const pub = pubEl ? pubEl.value : "any";

  const distEl = document.querySelector('input[name="dist"]:checked');
  const dist = distEl ? distEl.value : "any";

  const q = (listingState.searchQuery || "").trim().toLowerCase();
  const locNeedle = (listingState.locationNeedle || "").trim();

  let min = listingState.salaryMin;
  let max = listingState.salaryMax;

  return jobs.filter((job) => {
    if (q) {
      const blob = `${job.title} ${job.company} ${job.location}`.toLowerCase();
      if (!blob.includes(q)) return false;
    }

    if (locNeedle) {
      if (!job.location.includes(locNeedle)) return false;
    }

    if (langs.length) {
      const ok = langs.some((l) => job.languages.includes(l));
      if (!ok) return false;
    }

    if (pub !== "any") {
      const maxDays = parseInt(pub, 10);
      if (job.postedDays > maxDays) return false;
    }

    if (edu.length) {
      const ok = edu.some((e) => job.education.includes(e));
      if (!ok) return false;
    }

    if (jobTypes.length) {
      const ok = jobTypes.some((t) => job.tags.includes(t));
      if (!ok) return false;
    }

    if (dist !== "any") {
      const maxKm = parseInt(dist, 10);
      if (job.distanceKm > maxKm) return false;
    }

    if (min != null && !Number.isNaN(min) && job.salaryValue < min) return false;
    if (max != null && !Number.isNaN(max) && job.salaryValue > max) return false;

    if (workModes.length) {
      const ok = workModes.some((m) => job.tags.includes(m));
      if (!ok) return false;
    }

    return true;
  });
}

function sortJobs(jobs, sortKey) {
  const copy = [...jobs];
  if (sortKey === "salary") {
    copy.sort((a, b) => b.salaryValue - a.salaryValue);
  } else if (sortKey === "title") {
    copy.sort((a, b) => a.title.localeCompare(b.title, "ar"));
  } else {
    copy.sort((a, b) => a.postedDays - b.postedDays);
  }
  return copy;
}

function renderPagination(total, page, pageSize) {
  const ul = document.getElementById("jobs-pagination");
  const wrap = document.getElementById("jobs-pagination-wrap");
  if (!ul || !wrap) return;

  if (total === 0) {
    ul.innerHTML = "";
    wrap.classList.add("hidden");
    return;
  }

  const pages = Math.max(1, Math.ceil(total / pageSize));
  const p = Math.min(Math.max(1, page), pages);

  wrap.classList.remove("hidden");

  if (pages <= 1) {
    ul.innerHTML = `<li class="text-center text-sm text-gray-600">
      <span class="rounded-lg border border-gray-200 bg-white px-3 py-1.5">الصفحة 1 من 1 — جميع النتائج معروضة</span>
    </li>`;
    return;
  }

  const btnClass =
    "inline-flex h-9 min-w-9 items-center justify-center rounded-lg border border-gray-200 bg-white px-3 text-sm font-medium text-gray-700 hover:bg-gray-50";
  const activeClass =
    "inline-flex h-9 min-w-9 items-center justify-center rounded-lg bg-[var(--color-button)] px-3 text-sm font-semibold text-[var(--color-button-title)] hover:bg-[var(--color-button-hover)]";

  const parts = [];

  parts.push(`<li>
    <button type="button" data-page="${p - 1}" ${p <= 1 ? "disabled" : ""} class="${btnClass} disabled:opacity-40" aria-label="السابق">
      <svg class="h-4 w-4" aria-hidden="true" fill="none" viewBox="0 0 24 24"><path stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="m15 19-7-7 7-7" /></svg>
    </button>
  </li>`);

  const windowSize = 5;
  let start = Math.max(1, p - Math.floor(windowSize / 2));
  let end = Math.min(pages, start + windowSize - 1);
  if (end - start < windowSize - 1) start = Math.max(1, end - windowSize + 1);

  if (start > 1) {
    parts.push(`<li><button type="button" data-page="1" class="${btnClass}">1</button></li>`);
    if (start > 2) parts.push(`<li><span class="px-2 text-sm text-gray-500">…</span></li>`);
  }

  for (let i = start; i <= end; i++) {
    parts.push(`<li><button type="button" data-page="${i}" class="${i === p ? activeClass : btnClass}" ${i === p ? 'aria-current="page"' : ""}>${i}</button></li>`);
  }

  if (end < pages) {
    if (end < pages - 1) parts.push(`<li><span class="px-2 text-sm text-gray-500">…</span></li>`);
    parts.push(`<li><button type="button" data-page="${pages}" class="${btnClass}">${pages}</button></li>`);
  }

  parts.push(`<li>
    <button type="button" data-page="${p + 1}" ${p >= pages ? "disabled" : ""} class="${btnClass} disabled:opacity-40" aria-label="التالي">
      <svg class="h-4 w-4" aria-hidden="true" fill="none" viewBox="0 0 24 24"><path stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="m9 5 7 7-7 7" /></svg>
    </button>
  </li>`);

  ul.innerHTML = parts.join("");

  ul.querySelectorAll("button[data-page]").forEach((b) => {
    b.addEventListener("click", () => {
      const next = parseInt(b.getAttribute("data-page"), 10);
      if (!Number.isFinite(next) || next < 1 || next > pages) return;
      listingState.currentPage = next;
      applyListing();
      const grid = document.getElementById("jobs-grid");
      if (grid) grid.scrollIntoView({ behavior: "smooth", block: "start" });
    });
  });
}

/** يطابق ارتفاع صندوق الفلاتر مع شبكة البطاقات (شاشات lg فما فوق). */
function syncFiltersPanelHeight() {
  const grid = document.getElementById("jobs-grid");
  const panel = document.getElementById("filters-panel-card");
  if (!grid || !panel) return;
  if (!window.matchMedia("(min-width: 1024px)").matches) {
    panel.style.maxHeight = "";
    return;
  }
  const h = grid.offsetHeight;
  if (h > 0) panel.style.maxHeight = `${h}px`;
}

function applyListing() {
  const sortEl = document.getElementById("job-sort");
  const sortKey = sortEl ? sortEl.value : "recent";

  let list = filterJobs(getJobsList());
  list = sortJobs(list, sortKey);

  const total = list.length;

  const pages = Math.max(1, Math.ceil(total / PAGE_SIZE) || 1);
  if (listingState.currentPage > pages) listingState.currentPage = pages;

  const start = (listingState.currentPage - 1) * PAGE_SIZE;
  const pageSlice = list.slice(start, start + PAGE_SIZE);

  renderJobs(pageSlice);
  renderPagination(total, listingState.currentPage, PAGE_SIZE);
  requestAnimationFrame(() => {
    syncFiltersPanelHeight();
  });
}

function clearFilters() {
  document.querySelectorAll(".filter-control").forEach((el) => {
    if (el.type === "checkbox") el.checked = false;
  });
  const anyPub = document.querySelector('input[name="pub"][value="any"]');
  if (anyPub) anyPub.checked = true;
  const anyDist = document.querySelector('input[name="dist"][value="any"]');
  if (anyDist) anyDist.checked = true;
  const smin = document.getElementById("salary-min");
  const smax = document.getElementById("salary-max");
  if (smin) smin.value = "";
  if (smax) smax.value = "";
  listingState.salaryMin = null;
  listingState.salaryMax = null;
  listingState.searchQuery = "";
  listingState.locationNeedle = "";
  document.querySelectorAll("[data-job-search]").forEach((el) => {
    el.value = "";
  });
  document.querySelectorAll(".nav-location-select").forEach((el) => {
    el.selectedIndex = 0;
  });
  const sortEl = document.getElementById("job-sort");
  if (sortEl) sortEl.value = "recent";
  listingState.currentPage = 1;
}

function initFilterAccordion() {
  const root = document.getElementById("filters-accordion");
  if (!root) return;

  root.querySelectorAll("button[data-accordion-target]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const sel = btn.getAttribute("data-accordion-target");
      const panel = sel ? document.querySelector(sel) : null;
      if (!panel) return;

      const expanded = btn.getAttribute("aria-expanded") === "true";
      const next = !expanded;
      btn.setAttribute("aria-expanded", String(next));
      panel.classList.toggle("hidden", !next);

      const icon = btn.querySelector("[data-accordion-icon]");
      if (icon) icon.classList.toggle("rotate-180", next);
    });
  });
}

function initJobsListingPage() {
  const grid = document.getElementById("jobs-grid");
  if (!grid) return;

  initFilterAccordion();

  const syncSearchInputs = (value) => {
    document.querySelectorAll("[data-job-search]").forEach((el) => {
      if (el !== document.activeElement) el.value = value;
    });
  };

  const runSearch = () => {
    const first = document.querySelector("[data-job-search]");
    listingState.searchQuery = first ? first.value : "";
    listingState.currentPage = 1;
    applyListing();
  };

  document.querySelectorAll("[data-job-search]").forEach((el) => {
    el.addEventListener("input", () => {
      listingState.searchQuery = el.value;
      syncSearchInputs(el.value);
      listingState.currentPage = 1;
      applyListing();
    });
    el.addEventListener("search", runSearch);
  });

  document.getElementById("job-search-submit-desktop")?.addEventListener("click", runSearch);
  document.getElementById("job-search-submit-mobile")?.addEventListener("click", runSearch);

  const locInit = document.querySelector(".nav-location-select");
  if (locInit) listingState.locationNeedle = locInit.value || "";

  document.querySelectorAll(".nav-location-select").forEach((sel) => {
    sel.addEventListener("change", () => {
      listingState.locationNeedle = sel.value;
      document.querySelectorAll(".nav-location-select").forEach((s) => {
        if (s !== sel) s.value = sel.value;
      });
      listingState.currentPage = 1;
      applyListing();
    });
  });

  document.querySelectorAll(".filter-control").forEach((el) => {
    el.addEventListener("change", () => {
      listingState.currentPage = 1;
      applyListing();
    });
  });

  document.getElementById("salary-apply")?.addEventListener("click", () => {
    const minEl = document.getElementById("salary-min");
    const maxEl = document.getElementById("salary-max");
    const vMin = minEl && minEl.value !== "" ? parseInt(minEl.value, 10) : null;
    const vMax = maxEl && maxEl.value !== "" ? parseInt(maxEl.value, 10) : null;
    listingState.salaryMin = vMin;
    listingState.salaryMax = vMax;
    listingState.currentPage = 1;
    applyListing();
  });

  document.getElementById("clear-filters")?.addEventListener("click", (e) => {
    e.preventDefault();
    clearFilters();
    applyListing();
    if (e.currentTarget instanceof HTMLElement) e.currentTarget.blur();
  });

  document.getElementById("job-sort")?.addEventListener("change", () => {
    listingState.currentPage = 1;
    applyListing();
  });

  const panel = document.getElementById("filters-panel-card");
  if (panel && typeof ResizeObserver !== "undefined") {
    const ro = new ResizeObserver(() => syncFiltersPanelHeight());
    ro.observe(grid);
  }
  window.addEventListener("resize", syncFiltersPanelHeight);

  applyListing();
}

